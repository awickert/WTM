#!/usr/bin/env python3
"""Why BDF2-on-V drops to 1st order under recharge -- and the fix -- in one script.

BDF2-on-V (`-wtm_bdf2_on_V`) integrates the stored volume V(h) with a 3-level BDF2
difference and is genuinely 2nd order in time for the homogeneous (drainage)
problem. But every *production* run has recharge, and with recharge the measured
order collapses to 1. This script walks the diagnosis end to end, each step a
controlled A/B on the same deep smooth initial condition, and lands on the cause
and the fix. See benchmark/BDF2_RECHARGE_ORDER.md for the full narrative.

The story, one experiment per section (order = self-convergence vs a dt=0.25 yr ref):

  A. NO-CROSSING (recharge ON, but small enough that the water table stays below
     the land surface): order ~2. => Recharge itself is NOT the problem. A run
     with an active source integrates at 2nd order as long as nothing reaches
     wtd=0. This is the control that refutes the tempting "the recharge source
     is only 1st-order integrated" hypothesis (which was a stale-work-dir
     artifact; see the design note, section 13).

  B. CROSSING, surface water REMOVED (default collector): order ~1. Same IC, same
     solver -- only the recharge is now large enough to push cells up to wtd=0.
  C. CROSSING, surface water NOT removed (collector off): order ~2 TODAY, and this
     is a CHANGE. In 2026-07 the equivalent arm (evap_mode 1, water piling to
     +8.15 m) measured order ~1, and B-and-C-agree is what licensed the design
     note's claim that the order loss is not specific to how surface water is
     disposed of. It is now measured at +8.17 m -- the same state -- and order
     2.05/1.97/1.93. So the loss tracks REMOVAL holding cells at wtd=0, not
     crossing per se. (evap_mode itself is retired: frozen at 0, dropped by the
     config shim, unreachable -- B and C were emitting identical configs, so the
     agreement they showed was a duplicate rather than a result.) Cause of the
     change not established; leading candidate is 777326d, volume-based recharge.

  D. CROSSING + surface-kink smoothing: order ~1 (no help). Rounding the two C0
     coefficient kinks at the surface (ksat and storativity) does not restore
     order. => The cause is not a smoothable coefficient kink; it is the moving
     FREE BOUNDARY itself -- storativity jumps porosity->1 and T clamps at wtd=0,
     so a crossing cell's h(t) has a genuine temporal kink that BDF2 (which
     assumes C2) cannot see past, and the 1st-order error diffuses domain-wide.

  E. CROSSING + extended soil (`-wtm_extended_soil`): order ~2 RESTORED. Continue
     the aquifer above the surface (storativity=porosity everywhere, T never
     clamps, recharge always rech/porosity) so there is no jump and no free
     boundary. The GW step becomes smooth again and 2nd order returns. This is
     the fix -- and a model simplification (it deletes the surface special-casing
     inside the solver). Production truncates the above-surface mound back to real
     topography at the FSM/cycle handoff, not per GW step.

Isolation: this script builds and mutates its OWN fixture (a private inputs dir),
so it never clobbers -- and is never clobbered by -- the shared equil128_inputs
used by the other harnesses. Reusing a scratch dir across experiments that
overwrite the precip/IC tifs is exactly what produced the section-13 artifact.

NOTE: a benchmark diagnostic, NOT a unit test. It runs ~30 full model solves
(several minutes); it self-converges against a fine (dt=0.25 yr) reference.

Usage:   python3 recharge_free_boundary.py      # self-contained; builds its own fixture
"""
import glob, os, subprocess, sys
import numpy as np, rasterio
import paths  # noqa: F401
from paths import WTM, WORK

# --- Isolated fixture: a private inputs dir, generated by the canonical make_equil,
#     so nothing here touches the shared equil128_inputs (the stale-dir hazard). ---
PRIV = os.path.join(WORK, "rfb_work")
INP = os.path.join(PRIV, "equil128_inputs")
YEAR = 31536000
T = 1000                          # yr window
DTS = [1, 2, 5, 10, 100]          # yr; dt=0.25 is the reference
env = dict(os.environ, OMP_NUM_THREADS="1")

subprocess.run([sys.executable, os.path.join(os.path.dirname(__file__), "make_equil.py"), "128"],
               env=dict(env, WTM_WORK=PRIV), check=True, capture_output=True, text=True)
mask = rasterio.open(os.path.join(INP, "equil128_t0_mask.tif")).read(1) == 1
_pp = os.path.join(INP, "equil128_t0_precipitation.tif")
with rasterio.open(_pp) as s:
    _pprof = s.profile


def set_precip(P):
    with rasterio.open(_pp, "w", **_pprof) as d:
        d.write(np.full((128, 128), P, np.float32), 1)


# The config emitter the test suite uses: legacy "key value" lines in, nested YAML out. Going
# through it rather than hand-writing YAML here means this script rides along with any further
# schema change instead of being orphaned by the next one -- which is exactly what happened:
# this script wrote a flat .cfg, the config format migrated to nested YAML, and every model run
# began failing. See the note on check-the-run below for why that was invisible for so long.
EMIT = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "emit_config.sh")


def run(dt_yr, tag, supplied_wt, evap_mode, extra, collector=None):
    steps = int(round(T / dt_yr))
    cfg = os.path.join(PRIV, f"{tag}.yaml")
    # total_time, not total_cycles: with report_interval 1 the cycle count is T/dt, and the schema
    # takes the window directly. Same run, current vocabulary.
    flat = (
        f"run_type equilibrium\nfsm_on 0\nevap_mode {evap_mode}\ninfiltration_on 0\nrunoff_ratio 0\n"
        f"{f'runoff_collector {collector}' + chr(10) if collector else ''}"
        f"cells_per_degree 10\nsouthern_edge -45\ndeltat {int(dt_yr*YEAR)}\n"
        f"total_time {T}yr\nreport_interval 1\nfdepth_a 200\nfdepth_b 150\nfdepth_fmin 2\n"
        f"time_start t0\ntime_end t0\nsurfdatadir {INP}\nregion equil128\nsupplied_wt {supplied_wt}\n"
        # save_nreport_interval huge: WTM writes the first and LAST report regardless (verified: 80
        # reports -> 2 tifs, index 0 and index 80), so the final state is always available. Do not set
        # this to 1 "to be safe" -- at dt = 0.25 yr over 1000 yr that is 4000 tifs per run and ~120k
        # across the sweep, which is pure I/O for one field we actually read.
        f"textfilename {PRIV}/{tag}_log.txt\noutfile_prefix {PRIV}/{tag}_out_\nsave_nreport_interval 9999999\n")
    emitted = subprocess.run(["bash", EMIT], input=flat, capture_output=True, text=True, check=True)
    open(cfg, "w").write(emitted.stdout)
    # -wtm_eq_tol 0 DISABLES the equilibrium early-stop, and it is load-bearing for an order study.
    # An order is only meaningful between runs that cover the SAME model time. With the stop live, the
    # dt = 0.25 yr reference converged by the equilibrium metric and halted at 374.5 yr while every
    # coarser run went the full 1000 yr -- so "mean|err|" was a 626-year time gap, not a truncation
    # error. It read as ~5000 mm, identical at every dt (order 0.00) in EVERY arm, including the
    # control that must show order 2. A flat error is the signature: truncation error grows with dt,
    # a time offset does not.
    r = subprocess.run(["mpiexec", "-n", "1", WTM, cfg, "-wtm_eq_tol", "0", *extra],
                       capture_output=True, text=True, env=env)
    # CHECK THE RUN, LOUDLY. This used to swallow the model's exit status and return None when the
    # output was missing, so a failing model surfaced ~80 lines later as an AttributeError on a
    # NoneType -- a message pointing nowhere near the cause. A benchmark that cannot run must say so
    # in its own voice, at the point of failure, or the result it documents quietly becomes
    # unreproducible without anyone noticing.
    outs = sorted(glob.glob(os.path.join(PRIV, f"{tag}_out_*.tif")))
    if not outs:
        raise RuntimeError(
            f"model run '{tag}' produced no output (dt={dt_yr} yr, flags={' '.join(extra)}).\n"
            f"  exit={r.returncode}\n  config: {cfg}\n"
            f"  stderr tail: {(r.stderr or '').strip().splitlines()[-3:]}\n"
            f"  stdout tail: {(r.stdout or '').strip().splitlines()[-3:]}")
    return rasterio.open(outs[-1]).read(1)


def order_study(P, evap_mode, extra, label, note, collector=None):
    """One controlled order sweep: fine-dt reference then coarser dt, all identical
    but for dt. Prints mean|err| over land and the observed convergence order."""
    set_precip(P)
    ref = run(0.25, f"rfb_ref_{label}", 1, evap_mode, extra, collector)
    lo, hi = ref[mask].min(), ref[mask].max()
    print(f"\n=== {label}: {note} ===")
    print(f"    P={P} m/yr, evap_mode={evap_mode}, flags={' '.join(extra)}")
    print(f"    reference land wtd range [{lo:.2f}, {hi:.2f}] m  (0 => at the surface)")
    print(f"    {'dt(yr)':>7}{'mean|err|_mm':>14}{'order':>8}")
    prev = prevdt = None
    for dt in DTS:
        f = run(dt, f"rfb_{label}_{dt}", 1, evap_mode, extra, collector)
        m = np.abs(f - ref)[mask].mean()
        o = f"{np.log(m/prev)/np.log(dt/prevdt):.2f}" if prev else ""
        print(f"    {dt:>7}{m*1000:>14.4g}{o:>8}")
        prev, prevdt = m, dt


# --- Shared deep smooth initial condition: drain from the cold start (P=0), then
#     freeze it as supplied_wt. Every experiment below starts from this same field;
#     only the recharge and the solver flags differ. ---
set_precip(0.0)
smooth = run(0.25, "rfb_genIC", 0, 0, ["-wtm_bdf2_on_V"])
with rasterio.open(os.path.join(INP, "equil128_t0_topography.tif")) as t:
    prof = t.profile
prof.update(dtype="float64")
with rasterio.open(os.path.join(INP, "equil128_t0_starting_wt.tif"), "w", **prof) as d:
    d.write(smooth.astype("float64"), 1)
print(f"deep smooth IC: land wtd range [{smooth[mask].min():.2f}, {smooth[mask].max():.2f}] m")

V = ["-wtm_bdf2_on_V"]
SURF_SMOOTH = ["-wtm_ksat_surface_smoothing_width", "0.5",
               "-wtm_storativity_surface_smoothing_width", "0.5"]

# A. Recharge ON but sub-surface everywhere -> 2nd order (recharge itself is fine).
order_study(0.002, 0, V, "A_no_crossing",
            "recharge ON, water table stays below the surface -> expect order ~2")
# B/C. Recharge large enough to reach the surface -> 1st order, both disposal modes.
order_study(0.01, 0, V, "B_crossing_removed",
            "cells reach the surface, surface water REMOVED -> expect order ~1")
# C USED TO BE `evap_mode 1` AND IS NOW EXPRESSED WITH THE COLLECTOR. evap_mode is retired: the member
# is frozen at 0, the config shim DROPS the key (tests/emit_config.sh), and it is consulted only with
# -wtm_evap_taper off -- so `evap_mode 1` is unreachable and B and C were emitting BYTE-IDENTICAL
# configs. Two runs, one datum, and a "both disposal modes agree" conclusion drawn from a duplicate.
# The modern way to vary surface-water disposal is the collector, so C now runs with it OFF (nothing
# removes above-surface water) against B's default (water removed).
#
# THIS ARM'S ANSWER HAS CHANGED SINCE 2026-07-27, and that is the point of keeping it. Section 8 of
# BDF2_RECHARGE_ORDER.md records evap_mode 1 piling water to +8.15 m and STILL measuring order ~1,
# which is what licensed the claim that the order loss is not specific to how surface water is
# disposed of. Measured now: collector off piles to +8.17 m -- the same state -- and gives order
# 2.05/1.97/1.93 at 0.001313 mm. No-removal is SECOND order today. Cause not established; the leading
# candidate is 777326d (2026-08-14, volume-based recharge), which fixed surface-crossing recharge
# being re-scaled inconsistently per scheme. Consequence: the free-boundary order loss now appears
# tied to REMOVAL holding cells at wtd=0, not to crossing per se.
order_study(0.01, 0, V, "C_crossing_not_removed",
            "cells reach the surface, surface water ACCUMULATES -> was ~1 in 2026-07, now ~2",
            collector="off")
# D. Smoothing the surface coefficient kinks does not help (not a smoothable kink).
order_study(0.01, 0, V + SURF_SMOOTH, "D_kink_smoothing",
            "round the ksat & storativity kinks at wtd=0 -> expect NO help, order ~1")
# E. Extended soil removes the free boundary -> 2nd order restored (the fix).
# Extended soil is SELECTED AS A MODE, not layered on top of one. It is a member of
# surface_water.collection.method -- the same enumeration as active_set/implicit/explicit/off -- because
# it is a choice about what happens to water at the surface, and exactly one such choice can be in
# force. Its premise is that there IS no surface water: the aquifer continues upward and the mound is
# left standing until FSM truncates it at the cycle handoff. Asking for it AND a collector is
# contradictory, and the selector now says so and supersedes rather than letting both clamp.
# (`-wtm_extended_soil` is the legacy alias and selects this mode when no method is configured, so it
# also works alone; passing it alongside `collector="off"` would be superseded BY off and silently
# disable extended soil -- which is why this arm names the mode instead.)
# A-D keep their default collector on purpose: they NEED surface disposal, because it is disposal that
# holds cells AT wtd=0 and creates the moving free boundary whose kink costs them the order. Give A-D
# collector=off too and all four rise to order ~2 (measured: B 2.05/1.97/1.93, D 2.06/2.02/2.01) --
# the arms stop testing anything and E's order 2 proves nothing, since everything is order 2.
order_study(0.01, 1, V, "E_extended_soil",
            "continue the aquifer above the surface, no free boundary -> order ~2 RESTORED",
            collector="extended_soil")

set_precip(0.0)  # leave the private fixture at zero forcing
print("\nSummary: recharge is fine (A); REMOVING water at the surface breaks order (B), while")
print("letting it accumulate no longer does (C -- was ~1 in 2026-07, now ~2); it is the free")
print("boundary, not a smoothable kink (D); extending the soil restores order 2 (E).")
